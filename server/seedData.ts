// Helper to generate realistic variants
function createVariants(skuBase: string, color: string, hex: string, baseStock: number = 20, isKids: boolean = false) {
  const sizes = isKids ? ['UK 1', 'UK 2', 'UK 3', 'UK 4', 'UK 5'] : ['UK 6', 'UK 7', 'UK 8', 'UK 9', 'UK 10', 'UK 11'];
  return sizes.map((size, idx) => ({
    id: `v-${skuBase}-${idx + 1}`,
    sku: `${skuBase}-${size.replace(' ', '')}`,
    size,
    colorName: color,
    colorHex: hex,
    stockQuantity: Math.max(5, baseStock + (idx % 3) * 5),
  }));
}

